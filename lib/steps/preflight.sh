#!/bin/bash

step_preflight() {
    stage "系统初始化检查"

    if [ "$(whoami)" != "root" ]; then
        die "请使用 root 用户执行该脚本"
    fi
    progress "Root 权限检查通过"

    if ! command_exists apt; then
        die "当前实现仅支持 apt 系发行版"
    fi

    ARCH="$(uname -m)"
    progress "检测到架构: $ARCH"

    if has_systemd; then
        INIT_SYSTEM="systemd"
    else
        INIT_SYSTEM="non-systemd"
    fi

    if is_container; then
        CONTAINER_MODE=1
        progress "检测到容器环境"
    else
        CONTAINER_MODE=0
        progress "检测到宿主机环境"
    fi

    if is_wsl; then
        WSL_MODE=1
        progress "检测到 WSL 环境"
    else
        WSL_MODE=0
    fi

    if [ "$PROFILE_NAME" = "standard" ] && [ "${WSL_MODE:-0}" -ne 1 ]; then
        die "standard profile 仅支持 WSL 环境；非 WSL 宿主机请使用 --profile normal"
    fi

    if [ -n "${SUDO_USER:-}" ] && [ "${SUDO_USER:-}" != "root" ]; then
        LAUNCH_MODE="sudo-user"
        INVOKING_USER="$SUDO_USER"
        progress "检测到 sudo 用户上下文: $INVOKING_USER"
    else
        LAUNCH_MODE="root-session"
        INVOKING_USER="root"
        progress "检测到 root 会话上下文"
    fi

    if { [ "$PROFILE_NAME" = "standard" ] || [ "$PROFILE_NAME" = "normal" ]; } && [ "$LAUNCH_MODE" = "sudo-user" ]; then
        CREATE_USER=0
        TARGET_USER="$INVOKING_USER"
        TARGET_HOME="$(get_user_home "$TARGET_USER")"
        ENABLE_TEMP_SUDO=0
        FINAL_ACTION="none"
        progress "${PROFILE_NAME} profile 将复用当前 sudo 用户: $TARGET_USER"
    fi

    if [ "$PROFILE_NAME" = "autodl" ]; then
        CREATE_USER=0
        ENABLE_TEMP_SUDO=0

        if [ "$LAUNCH_MODE" = "sudo-user" ]; then
            TARGET_USER="$INVOKING_USER"
            TARGET_HOME="$(get_user_home "$TARGET_USER")"
            progress "autodl profile 将复用当前 sudo 用户: $TARGET_USER"
        else
            TARGET_USER="root"
            TARGET_HOME="/root"
            progress "autodl profile 将继续配置 root 用户"
        fi
    fi

    if [ "$CREATE_USER" -eq 0 ]; then
        TARGET_USER="${TARGET_USER:-root}"
        TARGET_HOME="${TARGET_HOME:-$(get_user_home "$TARGET_USER")}"
    fi
    if [ "$CREATE_USER" -eq 1 ] && [ "$FORCE_RECREATE_USER" -eq 0 ]; then
        local saved_user="${USER_NAME:-$(state_get choices target_user)}"
        if [ -n "$saved_user" ] && id "$saved_user" >/dev/null 2>&1; then
            CREATE_USER=0
            TARGET_USER="$saved_user"
            TARGET_HOME="$(get_user_home "$saved_user")"
            ENABLE_TEMP_SUDO=0
            progress "复用已初始化的用户: $TARGET_USER"
        fi
    fi
    if [ "$STATE_INITIALIZED" -eq 0 ] && [ -n "$TARGET_HOME" ] && [ -f "$TARGET_HOME/.zshrc" ] &&
        head -n 1 "$TARGET_HOME/.zshrc" | grep -q '^# Generated by FluxEnv'; then
        STATE_INITIALIZED=1
        progress "检测到旧版 FluxEnv 用户配置，将复用并接入历史记录"
    fi
}
