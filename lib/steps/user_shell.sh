validate_starship_config_for_user() {
    local user_home="$1"
    local config_path="$user_home/.config/starship.toml"

    if [ ! -f "$config_path" ] || ! starship_runs; then
        return 0
    fi

    if [ "${DRY_RUN:-0}" -eq 1 ]; then
        progress "校验 Starship 配置: $config_path"
        echo "    [dry-run] STARSHIP_CONFIG=$config_path starship module character"
        return 0
    fi

    progress "校验 Starship 配置: $config_path"
    if ! env STARSHIP_CONFIG="$config_path" starship module character >/dev/null 2>&1; then
        die "生成的 Starship 配置无效: $config_path"
    fi
}

install_plugin_dir_for_user() {
    local user_home="$1"
    local plugin_name="$2"
    local source_dir="$OFFLINE_DIR/$plugin_name"
    local target_dir="$user_home/.zsh/plugins/$plugin_name"
    local remote_url="$3"

    if [ -f "$target_dir/$plugin_name.zsh" ]; then
        progress "复用已有插件: $plugin_name ($user_home)"
        state_record "plugin:$target_dir" reused
        return 0
    fi
    if [ -e "$target_dir" ]; then
        [ -d "$target_dir" ] && [ ! -L "$target_dir" ] || die "插件路径不是普通目录: $target_dir"
        progress "插件入口缺失，保留已有文件并补齐: $target_dir"
        if [ -f "$source_dir/$plugin_name.zsh" ]; then
            managed_copy_missing "$source_dir" "$target_dir"
        elif [ "$ALLOW_ONLINE_FETCH" -eq 1 ]; then
            local temporary=""
            temporary="$(mktemp -d "${TMPDIR:-/tmp}/fluxenv-plugin.XXXXXX")"
            run_cmd "下载缺失插件资源" git clone --depth=1 "$remote_url" "$temporary/source"
            if [ "$DRY_RUN" -eq 0 ]; then
                managed_copy_missing "$temporary/source" "$target_dir"
                rm -rf "$temporary"
            else
                rmdir "$temporary"
            fi
        else
            die "无法修复缺失的插件入口: $plugin_name（ALLOW_ONLINE_FETCH=0）"
        fi
        [ "$DRY_RUN" -eq 1 ] || [ -f "$target_dir/$plugin_name.zsh" ] || die "修复后仍缺少插件入口: $plugin_name"
        state_record "plugin:$target_dir" applied
        return 0
    fi
    if [ -f "$source_dir/$plugin_name.zsh" ]; then
        copy_path "$source_dir" "$target_dir"
        state_record "plugin:$target_dir" applied
        return 0
    fi

    if [ "$ALLOW_ONLINE_FETCH" -eq 1 ]; then
        run_cmd "在线克隆 ${plugin_name}" git clone --depth=1 "$remote_url" "$target_dir"
        [ "$DRY_RUN" -eq 1 ] || [ -f "$target_dir/$plugin_name.zsh" ] || die "插件安装后缺少入口: $plugin_name"
        state_record "plugin:$target_dir" applied
        return 0
    fi

    die "缺少离线资源: ${plugin_name}，且 ALLOW_ONLINE_FETCH=0"
}

should_configure_root_user_state() {
    [ "${PROFILE_NAME:-}" = "normal" ] && \
        [ "${LAUNCH_MODE:-}" = "root-session" ] && \
        [ "${TARGET_USER:-}" != "root" ]
}

configure_shell_env_for_user() {
    local user_name="$1"
    local user_home="$2"

    progress "配置 shell 环境: $user_name ($user_home)"
    run_cmd "创建 shell 配置目录: $user_name" mkdir -p "$user_home/.zsh/plugins" "$user_home/.config" "$user_home/bin"

    install_plugin_dir_for_user "$user_home" "zsh-autosuggestions" "https://github.com/zsh-users/zsh-autosuggestions"
    install_plugin_dir_for_user "$user_home" "zsh-syntax-highlighting" "https://github.com/zsh-users/zsh-syntax-highlighting"

    local candidate=""
    local tool_bin="${UV_TOOL_BIN:-$user_home/.local/bin}"
    [ "$user_name" = "${TARGET_USER:-}" ] || tool_bin="$user_home/.local/bin"
    local quoted_bin=""
    printf -v quoted_bin '%q' "$tool_bin"
    local block="export PATH=$quoted_bin:\"\$PATH\""
    local node_body='export PNPM_HOME="${PNPM_HOME:-$HOME/.local/share/pnpm}"
typeset -U path
[ -d "$PNPM_HOME" ] && path=("$PNPM_HOME/bin" "$PNPM_HOME" $path)
export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
[ -s "$NVM_DIR/nvm.sh" ] && . "$NVM_DIR/nvm.sh"
nvm use --silent default >/dev/null 2>&1 || true'
    if [ "$user_name" = "${TARGET_USER:-}" ] && [ -n "${NVM_DIR:-}" ]; then
        local quoted_nvm=""
        local quoted_pnpm=""
        printf -v quoted_nvm '%q' "$NVM_DIR"
        printf -v quoted_pnpm '%q' "$PNPM_HOME"
        node_body="$(cat <<EOF
export PNPM_HOME=$quoted_pnpm
typeset -U path
[ ! -d "\$PNPM_HOME" ] || path=("\$PNPM_HOME/bin" "\$PNPM_HOME" \$path)
export NVM_DIR=$quoted_nvm
[ ! -s "\$NVM_DIR/nvm.sh" ] || . "\$NVM_DIR/nvm.sh"
nvm use --silent default >/dev/null 2>&1 || true
EOF
)"
    fi
    candidate="$(mktemp "${TMPDIR:-/tmp}/fluxenv-linux-shell.XXXXXX")"
    write_zshrc_for_user "$user_home" "$candidate"
    printf '\n%s\n%s\n%s\n' '# >>> fluxenv tools >>>' "$block" '# <<< fluxenv tools <<<' >> "$candidate"
    printf '\n%s\n%s\n%s\n' '# >>> fluxenv node >>>' "$node_body" '# <<< fluxenv node <<<' >> "$candidate"
    managed_install_file "$user_home/.zshrc" "$candidate"
    write_starship_config_for_user "$user_home" "$candidate"
    managed_install_file "$user_home/.config/starship.toml" "$candidate"
    rm -f "$candidate"

    managed_update_block "$user_home/.zshrc" '# >>> fluxenv tools >>>' '# <<< fluxenv tools <<<' "$block"
    managed_update_block "$user_home/.zshrc" '# >>> fluxenv node >>>' '# <<< fluxenv node <<<' "$node_body"
    validate_starship_config_for_user "$user_home"

    if [ "$user_name" != "root" ] && [ "${DRY_RUN:-0}" -eq 0 ]; then
        # Change only FluxEnv-owned paths, and only mismatched ownership.
        find "$user_home/.zsh" "$user_home/bin" ! -user "$user_name" -exec chown "$user_name:$user_name" {} +
        local owned_path=""
        for owned_path in "$user_home/.config" "$user_home/.zshrc" "$user_home/.config/starship.toml"; do
            find "$owned_path" -maxdepth 0 ! -user "$user_name" -exec chown "$user_name:$user_name" {} +
        done
    fi

    if [ "$CHANGE_DEFAULT_SHELL" -eq 1 ] && command_exists zsh; then
        local login_shell=""
        login_shell="$(getent passwd "$user_name" | cut -d: -f7)"
        if [ "$login_shell" != "$(command -v zsh)" ]; then
            run_cmd "设置 $user_name 默认 shell 为 zsh" chsh -s "$(command -v zsh)" "$user_name"
        fi
    fi
}

step_user() {
    stage "用户配置"

    if [ "$CREATE_USER" -eq 0 ]; then
        TARGET_USER="${TARGET_USER:-${INVOKING_USER:-root}}"
        TARGET_HOME="${TARGET_HOME:-$(get_user_home "$TARGET_USER")}"
        progress "当前 profile 使用现有用户: $TARGET_USER"
        state_put choices target_user "$TARGET_USER"
        state_record user reused
        return 0
    fi

    prompt_value USER_NAME "请输入用户名（字母开头，可含数字和下划线）" '^[a-zA-Z][a-zA-Z0-9_]*$'
    local recreate=0
    if id "$USER_NAME" >/dev/null 2>&1; then
        if [ "$FORCE_RECREATE_USER" -eq 1 ]; then
            [ "$USER_NAME" != root ] && [ "$USER_NAME" != "${INVOKING_USER:-root}" ] || die "不能重建当前登录用户"
            [ "$INTERACTIVE" -eq 1 ] || die "重建已有用户需要交互确认"
            prompt_yes_no "确认删除用户 $USER_NAME 及其家目录并重建？" n || die "已取消重建用户"
            recreate=1
        else
            TARGET_USER="$USER_NAME"
            TARGET_HOME="$(get_user_home "$TARGET_USER")"
            ENABLE_TEMP_SUDO=0
            progress "复用已有用户: ${TARGET_USER}，不修改密码或家目录"
            state_put choices target_user "$TARGET_USER"
            state_record user reused
            return 0
        fi
    fi

    prompt_password USER_PASSWORD "请设置用户密码"
    [ "$recreate" -eq 0 ] || run_cmd "删除旧用户 $USER_NAME" userdel -rf "$USER_NAME"
    run_cmd "创建用户 $USER_NAME" useradd "$USER_NAME" -G sudo -m -s /bin/zsh
    progress "设置用户密码"
    if [ "$DRY_RUN" -eq 0 ]; then
        printf '%s:%s\n' "$USER_NAME" "$USER_PASSWORD" | chpasswd
    fi

    TARGET_USER="$USER_NAME"
    TARGET_HOME="$(get_user_home "$TARGET_USER")"
    state_put choices target_user "$TARGET_USER"
    state_record user applied
}

step_sudo() {
    stage "Sudo 临时权限配置"
    state_cleanup

    if [ "$ENABLE_TEMP_SUDO" -ne 1 ]; then
        progress "当前 profile 跳过临时 sudo 配置"
        return 0
    fi

    managed_require_file /etc/sudoers.d/temp_install
    [ ! -e /etc/sudoers.d/temp_install ] || die "已有 temp_install sudo 配置，请先检查，避免覆盖"
    backup_path /etc/sudoers
    write_file /etc/sudoers.d/temp_install "0440" "" <<'EOF'
%sudo ALL=(ALL:ALL) NOPASSWD: ALL
Defaults visiblepw
EOF
    [ "$DRY_RUN" -eq 1 ] || state_record system/temp-sudo applied "$(state_file_signature /etc/sudoers.d/temp_install)"
}

state_cleanup() {
    [ "${STATE_ACTIVE:-0}" -eq 1 ] && [ "${DRY_RUN:-0}" -eq 0 ] || return 0
    local signature="$(state_get receipts system/temp-sudo)"
    if [ -n "$signature" ] && [ "$signature" != absent ] && [ -f /etc/sudoers.d/temp_install ]; then
        managed_require_file /etc/sudoers.d/temp_install
        if [ "$signature" = "$(state_file_signature /etc/sudoers.d/temp_install)" ]; then
            rm -f /etc/sudoers.d/temp_install
            state_put receipts system/temp-sudo absent
            state_event applied system/temp-sudo-cleanup
        else
            warn "临时 sudo 配置被手动修改，未删除: /etc/sudoers.d/temp_install"
        fi
    fi
}

step_shell_env() {
    stage "Shell 环境配置"

    install_starship || die "Starship 安装失败，请修复后重新运行"

    configure_shell_env_for_user "$TARGET_USER" "$TARGET_HOME"

    if should_configure_root_user_state; then
        configure_shell_env_for_user "root" "/root"
    fi
}

configure_vim_for_user() {
    local user_name="$1"
    local user_home="$2"

    progress "配置 Vim: $user_name ($user_home)"
    if [ -f "$user_home/.vimrc" ]; then
        progress "复用已有 Vim 配置和插件: $user_home"
        state_record "vim:$user_home" reused
        return 0
    fi
    if [ "$VIM_MODE" = "full" ] && [ -d "$OFFLINE_DIR/vim" ] && [ ! -e "$user_home/.vim" ]; then
        copy_path "$OFFLINE_DIR/vim" "$user_home/.vim"
        if [ -f "$user_home/.vim/.vimrc" ] && [ "${DRY_RUN:-0}" -eq 0 ]; then
            cp "$user_home/.vim/.vimrc" "$user_home/.vimrc"
        fi
    else
        write_file "$user_home/.vimrc" "0644" "" <<'EOF'
set number
set mouse=a
set smartindent
set tabstop=4
set expandtab
syntax on
EOF
    fi

    if [ "$VIM_MODE" = "full" ] && [ ! -e "$user_home/.vim/bundle/vundle" ]; then
        if [ -d "$OFFLINE_DIR/vundle" ]; then
            run_cmd "创建 Vundle 目录: $user_name" mkdir -p "$user_home/.vim/bundle"
            copy_path "$OFFLINE_DIR/vundle" "$user_home/.vim/bundle/vundle"
        elif [ "$ALLOW_ONLINE_FETCH" -eq 1 ]; then
            run_cmd "在线克隆 Vundle: $user_name" git clone https://gitee.com/hzx_3/vundle.git "$user_home/.vim/bundle/vundle"
        fi

        if [ "$INSTALL_VIM_PLUGINS" -eq 1 ] && [ -f "$user_home/.vimrc" ]; then
            try_cmd "安装 Vim 插件: $user_name" su - "$user_name" -c "vim +'BundleInstall' +qall >/dev/null 2>&1"
        fi
    fi
    state_record "vim:$user_home" applied

    if [ "$user_name" != "root" ] && [ "${DRY_RUN:-0}" -eq 0 ]; then
        chown -R "$user_name:$user_name" "$user_home/.vim" "$user_home/.vimrc" 2>/dev/null || true
    fi
}

step_vim() {
    stage "Vim 配置"

    if [ "$ENABLE_VIM" = ask ] && [ -n "$(state_get choices vim)" ]; then
        ENABLE_VIM="$(state_get choices vim)"
    fi
    if [ "${DRY_RUN:-0}" -eq 1 ] && [ "${ENABLE_VIM:-ask}" = "ask" ]; then
        ENABLE_VIM=1
        progress "dry-run 使用默认配置: ENABLE_VIM=1"
    else
        resolve_toggle ENABLE_VIM "是否配置 Vim 编辑器？" "n"
    fi

    VIM_ENABLED="$ENABLE_VIM"
    state_put choices vim "$VIM_ENABLED"
    if [ "$VIM_ENABLED" -ne 1 ]; then
        progress "跳过 Vim 配置"
        return 0
    fi

    linux_install_packages vim xclip astyle python3-setuptools
    configure_vim_for_user "$TARGET_USER" "$TARGET_HOME"

    if should_configure_root_user_state; then
        configure_vim_for_user "root" "/root"
    fi
}
