#!/bin/bash

render_proxy_exports() {
    local proxy_vars="http_proxy https_proxy HTTP_PROXY HTTPS_PROXY all_proxy ALL_PROXY no_proxy NO_PROXY"
    local var_name=""
    local value=""
    local rendered=""

    for var_name in $proxy_vars; do
        value="${!var_name:-}"
        if [ -n "$value" ]; then
            if [ -z "$rendered" ]; then
                rendered="# Inherit proxy settings captured during FluxEnv bootstrap"$'\n'
            fi
            rendered+="export ${var_name}=$(printf '%q' "$value")"$'\n'
        fi
    done

    printf '%s' "$rendered"
}

starship_runs() {
    command_exists starship && starship --version >/dev/null 2>&1
}

get_starship_archive_path() {
    local arch_name="${ARCH:-$(uname -m)}"
    local candidate=""

    case "$arch_name" in
        x86_64|amd64)
            candidate="$OFFLINE_DIR/starship-x86_64-unknown-linux-gnu.tar.gz"
            ;;
        aarch64|arm64)
            candidate="$OFFLINE_DIR/starship-aarch64-unknown-linux-gnu.tar.gz"
            ;;
        armv7l|armv7)
            candidate="$OFFLINE_DIR/starship-armv7-unknown-linux-gnueabihf.tar.gz"
            ;;
        *)
            candidate=""
            ;;
    esac

    if [ -n "$candidate" ] && [ -f "$candidate" ]; then
        printf '%s\n' "$candidate"
    fi
}

install_starship() {
    local archive_path=""

    if starship_runs; then
        progress "复用已有 Starship"
        STARSHIP_INSTALLED=1
        state_record tools/starship reused
        return 0
    fi

    archive_path="$(get_starship_archive_path)"
    if [ -n "$archive_path" ]; then
        if run_shell "安装 Starship 离线二进制" "tmpdir=\$(mktemp -d) && tar -xzf '$archive_path' -C \"\$tmpdir\" && install -m 0755 \"\$tmpdir/starship\" /usr/local/bin/starship && rm -rf \"\$tmpdir\""; then
            [ "$DRY_RUN" -eq 1 ] || starship_runs || die "Starship 安装后无法运行"
            STARSHIP_INSTALLED=1
            state_record tools/starship applied
            return 0
        fi

        warn "Starship 离线安装失败，已跳过"
        return 1
    fi

    warn "当前架构 ${ARCH:-unknown} 没有可用的 Starship 离线包"

    if [ -f "$OFFLINE_DIR/starship_install.sh" ] && [ "$ALLOW_ONLINE_FETCH" -eq 1 ]; then
        if try_cmd "执行本地 Starship 安装脚本" bash "$OFFLINE_DIR/starship_install.sh" -y; then
            [ "$DRY_RUN" -eq 1 ] || starship_runs || die "Starship 安装后无法运行"
            STARSHIP_INSTALLED=1
            state_record tools/starship applied
            return 0
        fi
    fi

    if [ "$ALLOW_ONLINE_FETCH" -eq 1 ]; then
        if try_shell "在线安装 Starship" "set -o pipefail; curl -fsSL https://starship.rs/install.sh | sh -s -- -y"; then
            [ "$DRY_RUN" -eq 1 ] || starship_runs || die "Starship 安装后无法运行"
            STARSHIP_INSTALLED=1
            state_record tools/starship applied
            return 0
        fi
    else
        warn "未启用在线抓取，已跳过 Starship 安装"
    fi

    return 1
}

write_zshrc_for_user() {
    local user_home="$1"
    local output_path="${2:-$user_home/.zshrc}"

    cat > "$output_path" <<EOF
# Generated by FluxEnv

export PATH="\$HOME/.local/bin:\$HOME/bin:/usr/local/bin:\$PATH"
export LC_ALL=en_US.UTF-8
export LANG=en_US.UTF-8
export FLUXENV_PROMPT_HOST="${HOST_NAME}"
$(render_proxy_exports)

# ==============================================
# 1. 初始化 Starship
# ==============================================
if command -v starship >/dev/null 2>&1 && starship --version >/dev/null 2>&1; then
    eval "\$(starship init zsh)"
fi

# ==============================================
# 2. 基础配置
# ==============================================
export CLICOLOR=1
export LSCOLORS=ExFxBxDxCxegedabagacad
alias ls='ls --color=auto'
alias ll='ls -lh --color=auto'
alias grep='grep --color=auto'
zstyle ':completion:*' list-colors "\${(s.:.)LS_COLORS}"

HISTFILE="\$HOME/.zsh_history"
HISTSIZE=10000
SAVEHIST=10000
setopt EXTENDED_HISTORY
setopt SHARE_HISTORY
setopt HIST_EXPIRE_DUPS_FIRST
setopt HIST_IGNORE_DUPS
setopt HIST_IGNORE_ALL_DUPS
setopt HIST_FIND_NO_DUPS
setopt HIST_IGNORE_SPACE
setopt HIST_SAVE_NO_DUPS
setopt HIST_REDUCE_BLANKS

autoload -Uz compinit
compinit

if [ -z "\${XDG_RUNTIME_DIR:-}" ]; then
    export XDG_RUNTIME_DIR="\${TMPDIR:-/tmp}/runtime-\$(id -u)"
    if [ ! -d "\$XDG_RUNTIME_DIR" ]; then
        mkdir -m 700 -p "\$XDG_RUNTIME_DIR" 2>/dev/null || true
    fi
fi

# ==============================================
# end. 加载插件 (必须放在文件最后)
# ==============================================
[ -f ~/.zsh/plugins/zsh-autosuggestions/zsh-autosuggestions.zsh ] && source ~/.zsh/plugins/zsh-autosuggestions/zsh-autosuggestions.zsh
[ -f ~/.zsh/plugins/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh ] && source ~/.zsh/plugins/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh
EOF
}

